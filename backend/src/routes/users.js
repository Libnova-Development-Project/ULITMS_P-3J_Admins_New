const router=require('express').Router();
const c=require('../controllers/userController');
const {auth,adminOnly}=require('../middleware/auth');
const {idParam,pagination}=require('../middleware/validate');
router.get('/',auth,adminOnly,pagination,c.list);
router.post('/',auth,adminOnly,c.create);
router.get('/:id/stats',auth,idParam,c.stats);
router.put('/:id/password',auth,idParam,c.changePassword);
router.put('/:id/status',auth,adminOnly,idParam,c.status);
router.delete('/:id',auth,adminOnly,idParam,c.remove);
router.get('/:id',auth,idParam,c.get);
router.put('/:id',auth,idParam,c.update);
module.exports=router;
